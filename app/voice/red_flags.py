"""Детектор красных флагов по регламенту РГ-ТЕЛ-01, раздел 7.4.

Две категории:
    A — угроза жизни → R-01 → рекомендация 103/112 + перевод P1.
    B — острое состояние → R-11 → перевод регистратору P1.

Принципы (из регламента):
    - Распознавание работает по смыслу, а не только по точным словам.
    - При сомнении — считать флаг сработавшим (ложная тревога допустима).
    - Распознавание не является оценкой состояния — это правило безопасности.

Что изменено относительно первой версии: шаблоны покрывают живую речь,
как её записывает ASR: «болит сердце», «не могу дышать», «потеряла сознание»,
«идёт кровь», «вызовите скорую», женский род и первое лицо. Те же имена
и тот же публичный интерфейс: detect(text) -> RedFlag | None.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from app.core.constants import (
    EMERGENCY_PHRASE,
    RED_FLAG_ALLERGY,
    RED_FLAG_BLEEDING,
    RED_FLAG_BREATHING,
    RED_FLAG_CATEGORY_A,
    RED_FLAG_CATEGORY_B,
    RED_FLAG_CHEST_PAIN,
    RED_FLAG_CHILD,
    RED_FLAG_CONSCIOUSNESS,
    RED_FLAG_HIGH_FEVER,
    RED_FLAG_MINOR_TRAUMA,
    RED_FLAG_PREGNANCY,
    RED_FLAG_SEIZURE,
    RED_FLAG_SELF_HARM,
    RED_FLAG_SEVERE_PAIN,
    RED_FLAG_STROKE,
    RED_FLAG_TRAUMA,
    RED_FLAG_WORSENING,
    URGENT_PHRASE,
)


@dataclass
class RedFlag:
    """Обнаруженный красный флаг."""

    category: str  # "A" или "B"
    group: str     # группа из раздела 7.4
    matched: str   # что именно сработало
    phrase: str    # что сказать пациенту


def _c(*patterns: str) -> list[re.Pattern[str]]:
    return [re.compile(p, re.IGNORECASE) for p in patterns]


# Глаголы «болит/давит/жмёт…» в разговорной речи
_PAIN_VERB = r"(?:болит|болят|колет|давит|жмёт|жмет|жжёт|жжет|сдавливает|щемит|прихватило|схватило)"
_HEART = r"(?:груд\w*|сердц\w*|грудин\w*)"

# ─────────────────────────────────────────────────────────────
# Категория А — угроза жизни
# ─────────────────────────────────────────────────────────────

_CATEGORY_A: dict[str, list[re.Pattern[str]]] = {
    RED_FLAG_CHEST_PAIN: _c(
        r"боль\w*\s+(?:в|за)\s+(?:груд|сердц)",
        rf"{_PAIN_VERB}\s+(?:у\s+меня\s+)?(?:в\s+|за\s+)?{_HEART}",
        rf"{_HEART}\s+(?:у\s+меня\s+)?(?:сильно\s+|очень\s+)?(?:{_PAIN_VERB}|останавлива\w*)",
        r"давит\s+за\s+грудин",
        r"отдаёт\s+в\s+левую\s+руку|отдает\s+в\s+левую\s+руку",
        r"сердечн\w+\s+приступ",
        r"\bинфаркт",
    ),
    RED_FLAG_BREATHING: _c(
        r"не\s+(?:может|могу|можем)\s+(?:нормально\s+)?дыша\w*",
        r"не\s+дыш\w+",
        r"нечем\s+дыша\w*",
        r"(?:трудно|тяжело)\s+дыша\w*",
        r"задыха\w+",
        r"синеет|посинел\w*",
        r"хрип\w+",
        r"подавил\w*с[яь]",
    ),
    RED_FLAG_CONSCIOUSNESS: _c(
        r"потерял\w*\s+сознани",
        r"теряю\s+сознани",
        r"без\s+сознани",
        r"не\s+приходит\s+в\s+себя",
        r"не\s+могу\s+разбудить",
        r"упал\w*\s+в\s+обморок",
        r"обморок",
    ),
    RED_FLAG_STROKE: _c(
        r"перекосил\w*\s+лиц",
        r"лицо\s+перекос\w+",
        r"отнял\w*с[яь]",
        r"не\s+(?:может|могу)\s+говорить",
        r"не\s+чувствует\s+(?:руку|ногу|половин)",
        r"речь\s+невнятн",
        r"онемел\w*\s+половин",
        r"\bинсульт",
    ),
    RED_FLAG_SEIZURE: _c(
        r"судорог",
        r"трясёт\s+(?:его|её|ее|ребён)|трясет\s+(?:его|её|ее|ребён)",
        r"припадок",
    ),
    RED_FLAG_BLEEDING: _c(
        r"кровотечени",
        r"кровь\s+(?:не\s+останавлива\w*|идёт|идет|течёт|течет|хлещет)",
        r"(?:идёт|идет|течёт|течет|хлещет)\s+кровь",
        r"рвот\w+\s+(?:с\s+)?кров",
        r"рвёт\s+кровью|рвет\s+кровью",
        r"кровь\s+изо\s+рта",
    ),
    RED_FLAG_TRAUMA: _c(
        r"\bДТП\b",
        r"ударил\w*с[яь]\s+голов",
        r"упал\w*\s+с\s+высот",
        r"ожог\w*\s+больш|сильн\w+\s+ожог",
        r"отрав\w+",
        r"проглотил\w*\s+(?:таблет|хими|батарейк|монет|лекарств)",
        r"укусил\w*\s+змея",
    ),
    RED_FLAG_ALLERGY: _c(
        r"отка\w+\s+горл|отёк\w*\s+(?:горл|лиц|язык)|отек\w*\s+(?:горл|лиц|язык)",
        r"не\s+(?:может|могу)\s+глотать",
        r"анафилактическ\w+\s+шок",
    ),
    RED_FLAG_CHILD: _c(
        r"младенец\s+вял",
        r"грудн\w+\s+ребён|грудн\w+\s+ребен",
        r"ребён\w+\s+(?:посинел|проглотил|не\s+дышит)|ребен\w+\s+(?:посинел|проглотил|не\s+дышит)",
    ),
    RED_FLAG_PREGNANCY: _c(
        r"беременн\w*.{0,40}(?:кровотечени|кровь|кровит)",
        r"(?:кровотечени|кровь|кровит).{0,40}беременн",
        r"отошли\s+воды",
        r"схватк",
        r"рожаю|роды\s+начались",
    ),
    RED_FLAG_SELF_HARM: _c(
        r"не\s+хочу\s+(?:больше\s+)?жить",
        r"покончить\s+с\s+собой|убить\s+себя|суицид",
        r"хочу\s+умереть|умираю|умирает",
        r"наглота\w+с[яь]\s+таблеток",
        r"угрожает\s+убить|убью\s+(?:его|её|ее|их)",
        # прямая просьба о неотложной помощи
        r"(?:вызов\w*|нужн\w+|срочно)\s+скор\w+",
        r"скор\w+\s+помощ",
    ),
}

# ─────────────────────────────────────────────────────────────
# Категория Б — острое состояние
# ─────────────────────────────────────────────────────────────

_CATEGORY_B: dict[str, list[re.Pattern[str]]] = {
    RED_FLAG_SEVERE_PAIN: _c(
        r"(?:очень\s+)?(?:сильн|остр|нестерпим|невыносим)\w+\s+боль",
        r"боль\s+(?:сильная|острая|нестерпимая|невыносимая)",
        r"(?:очень\s+сильно|нестерпимо|невыносимо|ужасно|жутко)\s+болит",
        r"сильно\s+болит|болит\s+(?:очень\s+)?сильно",
        r"невыносим\w+",
        r"боль\s+усилива",
    ),
    RED_FLAG_HIGH_FEVER: _c(
        r"температур\w*\s+(?:сорок|40|39|41|не\s+сбива\w*|третий\s+день)",
        r"температур\w*.{0,15}(?:тридцать\s+девять|сорок)",
    ),
    RED_FLAG_WORSENING: _c(
        r"стало\s+(?:очень\s+|намного\s+|резко\s+)?хуже",
        # «мне плохо слышно» — это про связь, а не про здоровье
        r"(?:мне|ему|ей|ребёнку|ребенку|мужу|жене|маме|папе)\s+(?:очень\s+)?(?:плохо|худо)\b(?!\s+(?:слыш|вид))",
        r"стало\s+(?:очень\s+)?плохо",
        r"резко\s+поднялось\s+давлени",
        r"кружится\s+голова.{0,20}не\s+могу\s+встать",
    ),
    RED_FLAG_MINOR_TRAUMA: _c(
        r"подвернул\w*\s+ног",
        r"порезал\w*с[яь]\s+глубоко",
    ),
}


def detect(text: str) -> RedFlag | None:
    """Найти красный флаг в реплике пациента.

    Сначала категория А (угроза жизни), потом Б. Срабатывает первое совпадение.
    """
    if not text:
        return None

    for group, patterns in _CATEGORY_A.items():
        for pattern in patterns:
            match = pattern.search(text)
            if match:
                return RedFlag(
                    category=RED_FLAG_CATEGORY_A,
                    group=group,
                    matched=match.group(0),
                    phrase=EMERGENCY_PHRASE,
                )

    for group, patterns in _CATEGORY_B.items():
        for pattern in patterns:
            match = pattern.search(text)
            if match:
                return RedFlag(
                    category=RED_FLAG_CATEGORY_B,
                    group=group,
                    matched=match.group(0),
                    phrase=URGENT_PHRASE,
                )

    return None